// File is one file of an export bundle.
type File struct {
	Name string
	Data []byte
	Mode int64
}

// Bundle is the input to Export.
type Bundle struct {
	Name     string  // base name; sanitised
	Template string  // template source
	Fixture  []byte  // fixture JSON
	Output   []byte  // rendered output; computed when nil
	Options  Options // format and delimiters
}

var nameRE = regexp.MustCompile(`[^A-Za-z0-9._-]+`)

// SafeName reduces s to a file name with no path separators.
func SafeName(s string) string {
	s = nameRE.ReplaceAllString(filepath.Base(s), "-")
	s = strings.Trim(s, ".-")
	if s == "" {
		return "template"
	}
	return s
}

// The bundle's run.go is generated by a template with [[ ]] delimiters so
// the Go source it emits can contain {{ }} freely.
var runTmpl = template.Must(template.New("run.go").Delims("[[", "]]").Parse(`// Command run re-renders [[.Tmpl]] against [[.Fixture]] with the same
// engine and function library tmplforge used, then writes the result to
// standard output. Generated by tmplforge export; edit freely.
//
//	go run . > [[.Output]].new && cmp [[.Output]] [[.Output]].new
package main

import (
	"encoding/json"
	htmltemplate "html/template"
	"fmt"
	"io"
	"os"
	"text/template"
)

const (
	tmplFile    = [[printf "%q" .Tmpl]]
	fixtureFile = [[printf "%q" .Fixture]]
	format      = [[printf "%q" .Format]]
	left, right = [[printf "%q" .Left]], [[printf "%q" .Right]]
)

type executor interface{ Execute(io.Writer, any) error }

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "run:", err)
		os.Exit(1)
	}
}

func run() error {
	src, err := os.ReadFile(tmplFile)
	if err != nil {
		return err
	}
	f, err := os.Open(fixtureFile)
	if err != nil {
		return err
	}
	defer f.Close()
	d := json.NewDecoder(f)
	d.UseNumber()
	data := map[string]any{}
	if err := d.Decode(&data); err != nil && err != io.EOF {
		return err
	}
	Normalize(data)
	var t executor
	if format == "html" {
		t, err = htmltemplate.New(tmplFile).Delims(left, right).Funcs(htmltemplate.FuncMap(All())).Parse(string(src))
	} else {
		t, err = template.New(tmplFile).Delims(left, right).Funcs(All()).Parse(string(src))
	}
	if err != nil {
		return err
	}
	return t.Execute(os.Stdout, data)
}
`))

var makeTmpl = template.Must(template.New("Makefile").Delims("[[", "]]").Parse(`# Generated by tmplforge export. Recipes use tabs.
OUT = [[.Output]]

all: check

render:
	go run . > $(OUT).new

check: render
	cmp $(OUT) $(OUT).new
	sha256sum -c SHA256SUMS

clean:
	rm -f $(OUT).new

.PHONY: all render check clean
`))

// ExportFiles builds the bundle in memory: template, fixture, golden
// output, a standalone run.go (plus a copy of the function library and a
// go.mod, so it builds with no network), a Makefile and SHA256SUMS. The
// file set is sorted; SHA256SUMS covers every other file.
func ExportFiles(b Bundle) ([]File, error) {
	name := SafeName(b.Name)
	format := b.Options.Format
	if format == "" {
		format = "txt"
	}
	if !ValidFormat(format) {
		return nil, fmt.Errorf("%w %q", ErrFormat, format)
	}
	fixture := b.Fixture
	if len(bytes.TrimSpace(fixture)) == 0 {
		fixture = []byte("{}\n")
	}
	out := b.Output
	if out == nil {
		data, err := LoadFixture(bytes.NewReader(fixture))
		if err != nil {
			return nil, err
		}
		if out, err = Render(b.Template, data, b.Options); err != nil {
			return nil, fmt.Errorf("export: %w", err)
		}
	}
	tmplName := name + ".tmpl"
	// The output keeps the name's own extension (hello.c, Makefile.txt);
	// a bare name gets the format's (untitled -> untitled.txt).
	outName := name
	if filepath.Ext(name) == "" {
		outName = name + Ext[format]
	}
	p := struct{ Tmpl, Fixture, Output, Format, Left, Right string }{
		tmplName, "fixture.json", outName, format, b.Options.Left, b.Options.Right,
	}
	var run, mk bytes.Buffer
	if err := runTmpl.Execute(&run, p); err != nil {
		return nil, err
	}
	if err := makeTmpl.Execute(&mk, p); err != nil {
		return nil, err
	}
	files := []File{
		{Name: tmplName, Data: []byte(b.Template)},
		{Name: "fixture.json", Data: fixture},
		{Name: outName, Data: out},
		{Name: "run.go", Data: run.Bytes()},
		{Name: "Makefile", Data: mk.Bytes()},
		{Name: "go.mod", Data: []byte("module tmplforge.bundle/" + strings.ToLower(strings.ReplaceAll(name, ".", "-")) + "\n\ngo 1.24\n")},
	}
	for _, f := range []string{"funcs.go", "yaml.go"} {
		src, err := fs.ReadFile(funcs.Source, f)
		if err != nil {
			return nil, err
		}
		src = bytes.Replace(src, []byte("\npackage funcs\n"), []byte("\npackage main\n"), 1)
		src = bytes.Replace(src, []byte("package funcs\n"), []byte("package main\n"), 1)
		files = append(files, File{Name: f, Data: src})
	}
	sort.Slice(files, func(i, j int) bool { return files[i].Name < files[j].Name })
	var sums bytes.Buffer
	for _, f := range files {
		h := sha256.Sum256(f.Data)
		fmt.Fprintf(&sums, "%s  %s\n", hex.EncodeToString(h[:]), f.Name)
	}
	files = append(files, File{Name: "SHA256SUMS", Data: sums.Bytes()})
	for i := range files {
		files[i].Mode = 0o644
	}
	return files, nil
}

// Export writes the bundle into dir, creating it.
func Export(dir string, b Bundle) ([]File, error) {
	files, err := ExportFiles(b)
	if err != nil {
		return nil, err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return nil, err
	}
	for _, f := range files {
		if err := os.WriteFile(filepath.Join(dir, f.Name), f.Data, os.FileMode(f.Mode)); err != nil {
			return nil, err
		}
	}
	return files, nil
}

// WriteTarGz writes files as a gzipped tar under prefix/. The modification
// time is fixed (SOURCE_DATE_EPOCH semantics) so the archive is
// reproducible: same inputs, same bytes.
func WriteTarGz(w io.Writer, prefix string, files []File) error {
	zw := gzip.NewWriter(w)
	tw := tar.NewWriter(zw)
	mtime := time.Unix(0, 0).UTC()
	for _, f := range files {
		hdr := &tar.Header{
			Name:    prefix + "/" + f.Name,
			Mode:    f.Mode,
			Size:    int64(len(f.Data)),
			ModTime: mtime,
			Format:  tar.FormatPAX,
		}
		if err := tw.WriteHeader(hdr); err != nil {
			return err
		}
		if _, err := tw.Write(f.Data); err != nil {
			return err
		}
	}
	if err := tw.Close(); err != nil {
		return err
	}
	return zw.Close()
}
