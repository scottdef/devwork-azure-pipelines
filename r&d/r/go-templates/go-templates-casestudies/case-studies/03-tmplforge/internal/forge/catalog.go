package forge

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io/fs"
	"sort"
	"strings"
	"text/template"

	"github.com/CoolGitOrg/tmplforge/catalog"
)

// Entry describes one catalog template (catalog/index.json).
type Entry struct {
	Name        string `json:"name"`
	File        string `json:"file"`
	Format      string `json:"format"`
	Description string `json:"description"`
	Delims      string `json:"delims,omitempty"`
	Fixture     string `json:"fixture"`
	Output      string `json:"output"`
}

// Catalog is the embedded set of starter templates.
type Catalog struct {
	FS      fs.FS
	Entries []Entry
	byName  map[string]int
}

// LoadCatalog reads index.json from the embedded catalog.
func LoadCatalog() (*Catalog, error) { return OpenCatalog(catalog.FS) }

// OpenCatalog reads index.json from any fs.FS laid out like catalog/.
func OpenCatalog(fsys fs.FS) (*Catalog, error) {
	b, err := fs.ReadFile(fsys, "index.json")
	if err != nil {
		return nil, fmt.Errorf("catalog: %w", err)
	}
	c := &Catalog{FS: fsys, byName: map[string]int{}}
	if err := json.Unmarshal(b, &c.Entries); err != nil {
		return nil, fmt.Errorf("catalog index: %w", err)
	}
	sort.Slice(c.Entries, func(i, j int) bool { return c.Entries[i].Name < c.Entries[j].Name })
	for i, e := range c.Entries {
		if _, dup := c.byName[e.Name]; dup {
			return nil, fmt.Errorf("catalog index: duplicate name %q", e.Name)
		}
		if !ValidFormat(e.Format) {
			return nil, fmt.Errorf("catalog %s: %w %q", e.Name, ErrFormat, e.Format)
		}
		c.byName[e.Name] = i
	}
	return c, nil
}

// Lookup returns the entry called name.
func (c *Catalog) Lookup(name string) (Entry, bool) {
	i, ok := c.byName[name]
	if !ok {
		return Entry{}, false
	}
	return c.Entries[i], true
}

// Source returns the template text of e.
func (c *Catalog) Source(e Entry) (string, error) {
	b, err := fs.ReadFile(c.FS, e.File)
	return string(b), err
}

// Fixture returns e's fixture, decoded.
func (c *Catalog) Fixture(e Entry) (map[string]any, error) {
	b, err := fs.ReadFile(c.FS, e.Fixture)
	if err != nil {
		return nil, err
	}
	return LoadFixture(bytes.NewReader(b))
}

// FixtureRaw returns e's fixture as stored.
func (c *Catalog) FixtureRaw(e Entry) ([]byte, error) { return fs.ReadFile(c.FS, e.Fixture) }

// Options returns render options for e with the given FuncMap source.
func (e Entry) Options() (Options, error) {
	l, r, err := ParseDelims(e.Delims)
	if err != nil {
		return Options{}, err
	}
	return Options{Name: e.Output, Format: e.Format, Left: l, Right: r}, nil
}

// catalogMD uses <% %> delimiters: its prose talks about both {{ }} and [[ ]].
var catalogMD = template.Must(template.New("CATALOG.md").Delims("<%", "%>").Funcs(template.FuncMap{
	"cell": func(s string) string { return strings.ReplaceAll(s, "|", `\|`) },
	"code": func(s string) string { return "`" + s + "`" },
}).Parse(`# Catalog

<!-- Generated by ` + "`make docs`" + ` (go run ./catalog/gendoc) from catalog/index.json. Do not edit. -->

<%len .%> starter templates are embedded in the binary. Each has a fixture
(catalog/fixtures/) and a golden output (testdata/golden/catalog/) that
` + "`go test ./internal/forge -run CatalogGolden`" + ` checks on every build.
Load one with ` + "`c NAME`" + ` in ` + "`tmplforge sh`" + `, open it from the GUI's front
page, or print it with ` + "`tmplforge catalog -src NAME`" + `.

Entries with ` + "`[[,]]`" + ` delimiters produce files that contain ` + "`{{ }}`" + ` of their own
(GitHub Actions ` + "`${{ }}`" + `, Prometheus ` + "`{{ $labels }}`" + `, CoreDNS and
consul-template); the alternate delimiters let both coexist.

| Name | Format | Delims | Description |
|---|---|---|---|
<%- range .%>
| [<%code .Name%>](../catalog/<%.File%>) | <%.Format%> | <%if .Delims%><%code .Delims%><%else%>-<%end%> | <%cell .Description%> |
<%- end%>
`))

// Markdown renders the catalog index as docs/CATALOG.md.
func (c *Catalog) Markdown() ([]byte, error) {
	var b bytes.Buffer
	err := catalogMD.Execute(&b, c.Entries)
	return b.Bytes(), err
}
